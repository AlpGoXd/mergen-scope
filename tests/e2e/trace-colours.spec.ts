import { test, expect } from '@playwright/test';
import { resolve } from 'node:path';
import { addAnalysis } from './analysis-helpers';

test('created traces have distinct colours and symbols can be shown', async ({ page }) => {
  await page.goto('/app.html');
  page.on('dialog', dialog => dialog.accept());
  await page.getByTestId('app-open-input').setInputFiles(resolve('test files/cascade_ip3_-12dBm.DAT'));
  await page.getByTestId('app-open-input').setInputFiles(resolve('test files/cascaded chain.s2p'));
  const rows = page.locator('[data-testid^="trace-row-"]');
  await expect(rows.first()).toBeVisible();
  const swatchColor = (row: typeof rows) => row.locator('.lp-swatch').evaluate(element => getComputedStyle(element).backgroundColor);
  const firstColor = await swatchColor(rows.first());
  const secondColor = await swatchColor(rows.nth(1));
  expect(firstColor).not.toBe(secondColor);
  const survivorId = await rows.last().getAttribute('data-testid');
  expect(survivorId).toBeTruthy();
  const survivor = page.getByTestId(survivorId ?? 'missing-trace');
  const survivorColor = await swatchColor(survivor);
  await page.getByRole('button', { name: 'Remove cascade_ip3_-12dBm.DAT' }).click();
  await expect(survivor).toBeVisible();
  expect(await swatchColor(survivor)).toBe(survivorColor);
  await survivor.click();
  const card = await addAnalysis(page, 'Smooth');
  await card.getByRole('button', { name: 'Create trace' }).click();
  const created = page.locator('[data-testid^="trace-row-"]').filter({ has: page.locator('.lp-trace.is-created') }).last();
  await expect(created).toBeVisible();
  expect(await swatchColor(created)).not.toBe(await swatchColor(survivor));
  await page.getByRole('button', { name: 'Settings', exact: true }).click();
  await page.getByRole('button', { name: 'Always', exact: true }).click();
  await expect(page.getByTestId('trace-symbol').first()).toBeVisible();
  const swatch = survivor.locator('.lp-swatch');
  await expect(swatch.locator('svg line')).toHaveCount(1);
  const box = await swatch.boundingBox();
  const g = await swatch.locator('svg path').evaluate(el => { const b = (el as SVGGraphicsElement).getBBox(); return { x: b.x, y: b.y, w: b.width, h: b.height }; });
  expect(box?.width).toBe(16); expect(box?.height).toBe(12);
  expect(g.x - 0.75).toBeGreaterThanOrEqual(-8); expect(g.y - 0.75).toBeGreaterThanOrEqual(-6);
  expect(g.x + g.w + 0.75).toBeLessThanOrEqual(8); expect(g.y + g.h + 0.75).toBeLessThanOrEqual(6);
  expect(Math.abs(g.x + g.w / 2)).toBeLessThan(0.5); expect(Math.abs(g.y + g.h / 2)).toBeLessThan(0.5);
});
